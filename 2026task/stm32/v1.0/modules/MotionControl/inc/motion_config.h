#define FF_K_FRICTION           300.0f

/**
 * @brief 静摩擦补偿 (PWM)
 *
 * @category C: 经验调参（需要实验标定）
 *
 * @value 80.0f PWM
 *
 * @origin 经验估计（待实车标定）
 *   - 前馈目的: 克服静止到启动时的最大静摩擦力
 *   - 静摩擦力通常大于动摩擦力
 *
 * @validation 标定方法
 *   方法: 最小启动PWM测试
 *   1. 小车静止，编码器清零
 *   2. 从PWM=0开始，每次增加5，观察轮子是否转动
 *   3. 记录轮子刚开始转动时的PWM值
 *   4. 重复测试5次取平均值
 *   5. FF_K_STATIC = 平均启动PWM × 1.2 (留20%余量)
 *
 *   示例:
 *   - 测试结果: 65, 68, 70, 67, 65 PWM
 *   - 平均值: 67 PWM
 *   - FF_K_STATIC = 67 × 1.2 ≈ 80 PWM
 *
 * @tuning_guide
 *   物理意义:
 *   - 从静止启动时，瞬间施加的PWM值
 *   - 只在速度接近0时施加（见FF_STATIC_DEADZONE）
 *
 *   建议范围: 50.0f ~ 150.0f
 *
 *   如何判断需要调整:
 *   - 启动困难，轮子不转 → 增大FF_K_STATIC
 *   - 启动时有明显冲击 → 减小FF_K_STATIC
 *   - 最佳状态: 平滑启动，无延迟
 *
 *   注意事项:
 *   - 左右轮的静摩擦可能不同（制造差异）
 *   - 当前实现对左右轮使用相同值
 *   - 如果启动时偏向严重，可能需要分别标定
 *
 * @history
 *   - 初始值: 80.0f (理论估计)
 *   - 待实车标定后更新
 *
 * @references
 *   - 标定方法详见: docs/PARAMETER_TUNING_GUIDE.md
 *
 * @warnings
 *   - 此参数对低速性能影响很大
 *   - 更换电机、轮胎或地面后需要重新标定
 */
#define FF_K_STATIC             80.0f

