/* ============================================================================
 * 控制频率配置
 * ---------------------------------------------------------------------------
 * 分层频率架构 (2026-07-30优化):
 * - 主循环频率: 500Hz (编码器采样)
 * - PID控制频率: 100Hz (匹配执行器响应时间~10ms)
 * - EKF/感知频率: 50Hz (计算密集型任务)
 *
 * 优化理由:
 * - 编码器保持500Hz高频采样确保速度估计精度
 * - PID降至100Hz节省CPU (电机PWM响应时间约10ms，100Hz充分)
 * - 原500Hz PID频率过高造成不必要的计算开销
 * ============================================================================ */

/**
 * @brief 主循环频率 (Hz) - 编码器采样频率
 *
 * @category D: 硬件约束参数（系统设计）
 *
 * @value 500 Hz
 *
 * @origin 系统设计
 *   - FreeRTOS任务周期: 2ms (1000 / 500 = 2ms)
 *   - 编码器采样需要高频以保证速度估计精度
 *   - 500Hz足够捕捉电机动态响应
 *
 * @validation
 *   - 确保主任务执行时间 < 2ms
 *   - 可通过性能监控工具验证
 *
 * @tuning_guide
 *   增大频率:
 *   - 优点: 速度估计更精确，响应更快
 *   - 缺点: CPU负载增加
 *   - 建议范围: 200Hz ~ 1000Hz
 *
 *   减小频率:
 *   - 优点: CPU负载降低
 *   - 缺点: 速度估计精度下降，延迟增加
 *
 * @warnings
 *   - 修改此值需要同步修改FreeRTOS任务周期
 *   - 必须确保任务执行时间 < 周期时间
 */
#define MAIN_LOOP_FREQ_HZ       500

/**
 * @brief PID控制器执行频率 (Hz)
 *
 * @category D: 硬件约束参数（系统设计，已优化）
 *
 * @value 100 Hz
 *
 * @origin 系统优化 (2026-07-30)
 *   - 匹配执行器响应时间: TB6612电机驱动器响应时间约10ms
 *   - 100Hz = 10ms周期，与执行器响应时间一致
 *   - 优化理由: 之前的500Hz过高，造成不必要的计算开销
 *
 * @validation
 *   - 确保PID计算时间 < 10ms
 *   - 通过性能监控验证无超时
 *
 * @tuning_guide
 *   选择原则:
 *   - PID频率应匹配执行器响应频率
 *   - 过高: 浪费CPU，PID来不及看到效果就再次调整
 *   - 过低: 控制延迟增加，响应变慢
 *
 *   建议范围: 50Hz ~ 200Hz
 *   - 50Hz (20ms): 低速应用，节省CPU
 *   - 100Hz (10ms): 标准配置（当前）
 *   - 200Hz (5ms): 高速高精度应用
 *
 * @history
 *   - 之前: 500Hz（与主循环相同）
 *   - 2026-07-30: 优化为100Hz（降低CPU负载）
 *
 * @references
 *   - logs/2026-07-30_optimization_recommendation.md
 *
 * @warnings
 *   - 修改此值需要重新调整PID参数（特别是Ki和Kd）
 *   - 必须是MAIN_LOOP_FREQ_HZ的整数除数
 */
#define PID_CONTROL_FREQ_HZ     100

/** @brief PID控制周期 (秒) - 用于积分/微分计算 */
#define PID_CONTROL_PERIOD_S    (1.0f / PID_CONTROL_FREQ_HZ)

/** @brief 主循环周期 (秒) - 用于编码器速度估计 */
#define MAIN_LOOP_PERIOD_S      (1.0f / MAIN_LOOP_FREQ_HZ)

/** @brief 保持兼容性：默认控制周期指PID周期 */
#define CONTROL_FREQ_HZ         PID_CONTROL_FREQ_HZ
#define CONTROL_PERIOD_S        PID_CONTROL_PERIOD_S

/** @brief PID控制分频系数 - 主循环每N次执行一次PID */
#define PID_CONTROL_DIVIDER     (MAIN_LOOP_FREQ_HZ / PID_CONTROL_FREQ_HZ)

/* ============================================================================
 * 轮速PI反馈参数
 * ---------------------------------------------------------------------------
 * 调参要点:
 *   - 先调 SPEED_KP: 逐渐增大直到速度响应快速无振荡
 *   - 再调 SPEED_KI: 消除稳态误差，不宜过大否则会低频摆动
 *   - 反馈输出限幅 SPEED_OUTPUT_MAX 保护电机不过流
 * ============================================================================ */

/**
 * @brief 轮速控制比例增益
 *
 * @category C: 经验调参（需要实验）
 *
 * @value 200.0f
 *
 * @origin 经验调参（待实车验证）
 *   - 调参方法: 试凑法
 *   - 调参依据: 阶跃响应测试
 *   - 当前状态: 初始估计值，待实车优化
 *
 * @tuning_guide
 *   物理意义:
 *   - Kp决定系统响应速度
 *   - 速度误差1 m/s时，输出PWM增量 = 200
 *
 *   调参步骤（Ziegler-Nichols方法）:
 *   1. 设置Ki=0, Kd=0
 *   2. 从小值开始逐步增大Kp (50 → 100 → 150 → ...)
 *   3. 观察速度阶跃响应:
 *      - Kp太小: 响应慢，稳态误差大
 *      - Kp合适: 快速响应，轻微超调
 *      - Kp太大: 振荡，不稳定
 *   4. 找到临界Kp（开始持续振荡）
 *   5. 最终Kp = 临界Kp × 0.6
 *
 *   试凑法调参记录（待实车测试）:
 *   - 100.0f: 预计响应慢
 *   - 150.0f: 预计响应改善
 *   - 200.0f: 当前值（预估）
 *   - 250.0f: 可能过冲
 *
 *   建议范围: 100.0f ~ 300.0f
 *
 *   如何判断需要调整:
 *   - 响应太慢 → 增大Kp
 *   - 有振荡 → 减小Kp
 *   - 稳态误差大 → 检查Ki或增大Kp
 *
 * @validation
 *   阶跃响应测试:
 *   - 给定速度指令从0跃变到0.5 m/s
 *   - 观察实际速度响应曲线
 *   - 理想响应: 上升时间<0.5s, 超调<10%, 无振荡
 *
 * @history
 *   - 初始值: 200.0f (理论估计)
 *   - 待实车调试后更新
 *
 * @warnings
 *   - 更改控制频率后需要重新调整此参数
 *   - Kp过大会导致系统不稳定
 *   - 建议每次调整步长不超过20%
 */
#define SPEED_KP                200.0f

/**
 * @brief 轮速控制积分增益
 *
 * @category C: 经验调参（需要实验）
 *
 * @value 50.0f
 *
 * @origin 经验调参（待实车验证）
 *   - 调参方法: 试凑法
 *   - 调参依据: 消除稳态误差
 *   - 当前状态: 初始估计值，待实车优化
 *
 * @tuning_guide
 *   物理意义:
 *   - Ki决定消除稳态误差的能力
 *   - 积分项 = Ki × ∫error dt
 *   - 速度误差持续1秒时，积分输出增量 = 50 × 1 = 50 PWM
 *
 *   调参步骤:
 *   1. 先调好Kp，确保基本响应正常
 *   2. Ki从0开始逐步增大 (0 → 10 → 20 → 50 → ...)
 *   3. 观察稳态误差:
 *      - Ki=0: 有稳态误差（速度达不到目标）
 *      - Ki合适: 稳态误差消除，响应平稳
 *      - Ki太大: 低频振荡，超调增大
 *   4. 找到消除稳态误差的最小Ki值
 *
 *   建议范围: 10.0f ~ 100.0f
 *
 *   如何判断需要调整:
 *   - 有稳态误差（速度始终达不到目标）→ 增大Ki
 *   - 低频振荡（缓慢的来回摆动）→ 减小Ki
 *   - 启动时超调过大 → 减小Ki
 *
 *   常见问题:
 *   - 积分饱和: 当输出饱和时，积分项继续累积导致超调
 *   - 解决方法: 使用抗积分饱和（当前代码已实现）
 *
 * @validation
 *   稳态误差测试:
 *   - 给定恒定速度指令0.5 m/s
 *   - 等待系统稳定（5秒后）
 *   - 测量稳态速度误差
 *   - 理想结果: 误差 < 0.01 m/s (2%)
 *
 * @history
 *   - 初始值: 50.0f (理论估计)
 *   - 待实车调试后更新
 *
 * @warnings
 *   - Ki不宜过大，否则会引起积分饱和和超调
 *   - 更改控制频率后，Ki需要成比例调整
 *   - 如果频率加倍，Ki应减半
 */
#define SPEED_KI                50.0f

